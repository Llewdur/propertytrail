<?php

declare(strict_types=1);

namespace App\Http\Controllers\Marketing;

use App\Http\Controllers\Controller;
use App\Services\Marketing\SampleReportService;
use App\Support\PublicPage;
use Illuminate\Http\Response;

final class SampleReportController extends Controller
{
    public function __construct(
        private readonly SampleReportService $samples,
    ) {}

    public function __invoke(): Response
    {
        return response()
            ->view('marketing.sample-report', [
                'title' => 'See a sample inspection report',
                'description' => 'Download a real PDF generated by PropertyTrail using fictional property, people and room notes.',
            ])
            ->withHeaders(PublicPage::headers());
    }

    public function download(): Response
    {
        return response($this->samples->bytes(), Response::HTTP_OK, [
            'Content-Type' => 'application/pdf',
            'Content-Disposition' => 'attachment; filename="propertytrail-sample-report.pdf"',
            'Cache-Control' => 'no-store, no-cache, must-revalidate, max-age=0',
            'Pragma' => 'no-cache',
            'X-Content-Type-Options' => 'nosniff',
            'X-Frame-Options' => 'DENY',
            'X-Robots-Tag' => 'noindex, nofollow',
            'Content-Security-Policy' => "default-src 'none'; base-uri 'none'; frame-ancestors 'none'",
        ]);
    }
}
