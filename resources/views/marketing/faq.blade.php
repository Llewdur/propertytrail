<h1>Frequently asked questions</h1>
<p class="lede">Short answers about property condition records, evidence and the reports PropertyTrail produces.</p>

<h2>Getting started</h2>
<div class="card">
    <h3>What does PropertyTrail do?</h3>
    <p>It records the condition of a property room by room, keeps the photographs with the notes, collects both parties' signatures and generates a PDF report that stays with the property record.</p>
</div>
<div class="card">
    <h3>Do I need to print anything?</h3>
    <p>No. The checklist is on your phone and the signed report is a PDF you can download and keep. If you prefer paper, our <a href="/resources">free checklist</a> prints cleanly.</p>
</div>

<h2>Condition and evidence</h2>
<div class="card">
    <h3>What is fair wear and tear?</h3>
    <p>It generally means the ordinary deterioration that happens through normal use over time, taking the age and condition of the item into account. It is different from damage. A condition record made at move-in and move-out gives both parties something concrete to discuss. This is general information, not legal advice.</p>
</div>
<div class="card">
    <h3>What if an inspection was missed at move-in?</h3>
    <p>You can still record the condition when you notice it. Note the date and why the earlier inspection was missed, and keep the record going forward. A later snapshot is more useful than no record at all.</p>
</div>
<div class="card">
    <h3>Are the photographs independently verified?</h3>
    <p>No. PropertyTrail records what was captured and when. It does not claim that photographs are independently verified or legally conclusive.</p>
</div>

<h2>Disputes and reports</h2>
<div class="card">
    <h3>Can a report be used in court?</h3>
    <p>A PropertyTrail report is a record of condition, not a legal opinion. Whether a document is accepted in a proceeding, and what weight it carries, is for the parties and their advisers to decide.</p>
</div>
<div class="card">
    <h3>What about a Rental Housing Tribunal complaint?</h3>
    <p>Keep the inspection record, photographs, signed report and any related correspondence together so you can provide them if a complaint is brought. PropertyTrail does not lodge complaints or give legal advice.</p>
</div>
<div class="card">
    <h3>Can I share the report with the other party?</h3>
    <p>Yes. Once the report is signed, a private link can be shared. You can revoke access later, and access events are recorded in the audit history.</p>
</div>

<h2>Privacy and plans</h2>
<div class="card">
    <h3>Who can see my property records?</h3>
    <p>Access is scoped to your organisation and the people assigned to the property. Private owner notes and tenant contact details are never exposed on a public report link. See the <a href="/privacy">privacy notice</a>.</p>
</div>
